"""Turn a hypothesis into a Shinka task directory with a frozen evaluator.

The evaluator is a single self-contained ``evaluate.py`` with the quant config
embedded, because Shinka copies it into the results directory before running
it. Its hash (and the data's hash) are recorded in the notebook.
"""

from __future__ import annotations

import hashlib
import shutil
from pathlib import Path
from typing import Tuple

import yaml

from shinka.research.notebook import (
    DataSplit,
    Experiment,
    ExperimentPlan,
    Notebook,
    experiment_dir,
)
from shinka.research.quant import QuantConfig, file_sha256, load_bars, split_index

EVALUATE_TEMPLATE = '''"""Frozen evaluator generated by shinka_research. Do not edit.

Any change to this file or to the data invalidates the experiment.
"""

import argparse

from shinka.research.quant import QuantConfig, run_quant_eval

CONFIG = QuantConfig.model_validate_json(
    r"""{config_json}"""
)

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--program_path", default="initial.py")
    parser.add_argument("--results_dir", default="results")
    args = parser.parse_args()
    _, correct, err = run_quant_eval(args.program_path, args.results_dir, CONFIG)
    print("correct" if correct else f"incorrect: {{err}}")
'''

SYS_MSG_TEMPLATE = """You are a quantitative researcher testing one hypothesis.

Hypothesis {hid}: {title}

{body}

Rules:
- Only edit code inside EVOLVE-BLOCK. `run_experiment(bars)` must return a pandas
  Series of target positions in [-1, 1] with the same index as `bars`.
- The position at bar t may only use information up to and including bar t.
  Look-ahead is detected automatically and makes the program incorrect.
- Stay within the spirit of the hypothesis: improve how it is expressed and
  exploited, do not swap in an unrelated strategy.
- You are scored on in-sample walk-forward Sharpe after transaction costs.
"""

SHINKA_CONFIG_FILENAME = "shinka.yaml"
DEV_DATA = Path("data") / "dev.csv"


def prepare_data(
    root: Path,
    nb: Notebook,
    source: Path | None,
    timestamp_col: str,
    lockbox_fraction: float,
) -> DataSplit:
    """Fix the direction's data on first use: split off the lockbox tail and
    write only the development part to ``data/dev.csv``."""
    if nb.data is not None:
        if source is not None and file_sha256(Path(source)) != nb.data.source_hash:
            raise ValueError(
                "this direction already uses other data; start a new direction"
            )
        return nb.data
    if source is None:
        raise ValueError("--data is required for the direction's first experiment")
    source = Path(source).resolve()
    bars = load_bars(source, timestamp_col)
    cut = split_index(len(bars), lockbox_fraction)
    if cut < 50 or cut >= len(bars):
        raise ValueError("not enough bars for the requested lockbox fraction")
    dev_path = (Path(root) / DEV_DATA).resolve()
    dev_path.parent.mkdir(parents=True, exist_ok=True)
    bars.iloc[:cut].to_csv(dev_path)
    nb.data = DataSplit(
        source_hash=file_sha256(source),
        timestamp_col=timestamp_col,
        dev_path=str(dev_path),
        n_total=len(bars),
        n_dev=cut,
        lockbox_start=str(bars.index[cut]),
    )
    return nb.data


def scaffold_experiment(
    root: Path,
    nb: Notebook,
    hid: str,
    initial_path: Path,
    cfg: QuantConfig,
) -> Tuple[Experiment, Path]:
    """Create task/ for a new experiment and record its hashes in the notebook."""
    root = Path(root)
    hyp = nb.get(hid)
    data_path = Path(cfg.data_path).resolve()
    if not data_path.exists():
        raise FileNotFoundError(data_path)
    cfg = cfg.model_copy(update={"data_path": str(data_path)})

    body = (root / "hypotheses" / f"{hid}.md").read_text()
    eid = f"e{len(hyp.experiments) + 1:02d}"
    task_dir = experiment_dir(root, hid, eid) / "task"
    if task_dir.exists():
        raise FileExistsError(task_dir)
    task_dir.mkdir(parents=True)
    shutil.copyfile(initial_path, task_dir / "initial.py")
    evaluate = task_dir / "evaluate.py"
    evaluate.write_text(
        EVALUATE_TEMPLATE.format(config_json=cfg.model_dump_json(indent=4))
    )

    sys_msg = SYS_MSG_TEMPLATE.format(hid=hid, title=hyp.title, body=body.strip())
    (task_dir / SHINKA_CONFIG_FILENAME).write_text(
        yaml.safe_dump({"evo": {"task_sys_msg": sys_msg}}, allow_unicode=True)
    )

    exp = nb.add_experiment(
        hid,
        evaluator_hash=file_sha256(evaluate),
        data_path=str(data_path),
        data_hash=file_sha256(data_path),
    )
    return exp, task_dir


def load_config(task_dir: Path) -> QuantConfig:
    """Read the config embedded in a frozen evaluate.py."""
    from shinka.core.wrap_eval import load_program

    return load_program(str(Path(task_dir) / "evaluate.py")).CONFIG


def task_message_sha256(task_dir: Path) -> str:
    """Hash of the task message Shinka gives the mutation model."""
    config = Path(task_dir) / SHINKA_CONFIG_FILENAME
    try:
        message = yaml.safe_load(config.read_text(encoding="utf-8"))["evo"][
            "task_sys_msg"
        ]
    except (OSError, yaml.YAMLError, KeyError, TypeError) as error:
        raise RuntimeError(f"{config}: task message unreadable ({error})") from None
    if not isinstance(message, str):
        raise RuntimeError(f"{config}: task message unreadable (not text)")
    return hashlib.sha256(message.encode("utf-8")).hexdigest()


def verify_experiment(root: Path, nb: Notebook, hid: str, exp: Experiment) -> None:
    """Raise if the evaluator or the development data changed and, for an
    experiment with a frozen plan, if anything the plan froze changed; the
    message names the file."""
    evaluate = experiment_dir(root, hid, exp.id) / "task" / "evaluate.py"
    if file_sha256(evaluate) != exp.evaluator_hash:
        raise RuntimeError(f"{evaluate}: evaluator was modified")
    if file_sha256(Path(exp.data_path)) != exp.data_hash:
        raise RuntimeError(f"{exp.data_path}: data changed since scaffolding")
    if exp.plan is not None:
        _verify_plan(Path(root), nb, hid, exp.id, exp.plan)


def _verify_plan(
    root: Path, nb: Notebook, hid: str, eid: str, plan: ExperimentPlan
) -> None:
    if plan.domain != nb.domain:
        raise RuntimeError(
            f"{hid}/{eid}: plan is for a {plan.domain} experiment in a "
            f"{nb.domain} direction"
        )
    base = root.resolve()
    for rel, digest in {**plan.checker.files, **plan.data.files}.items():
        path = (base / rel).resolve()
        if not path.is_relative_to(base):
            raise RuntimeError(f"{root / rel}: plan file is outside the direction")
        if not path.is_file():
            raise RuntimeError(f"{path}: plan file is missing")
        if file_sha256(path) != digest:
            raise RuntimeError(f"{path}: changed since the plan was frozen")
    task_dir = experiment_dir(root, hid, eid) / "task"
    if task_message_sha256(task_dir) != plan.task_message:
        raise RuntimeError(
            f"{task_dir / SHINKA_CONFIG_FILENAME}: task message changed since the "
            "plan was frozen"
        )
